    private static void AssertMatrix(string[] expected, QrCode? qr)
    {
        Assert.NotNull(qr);
        Assert.Equal(expected.Length, qr!.Size);
        for (int y = 0; y < expected.Length; y++)
        {
            var actual = new char[qr.Size];
            for (int x = 0; x < qr.Size; x++) actual[x] = qr.Get(x, y) ? '1' : '0';
            Assert.Equal(expected[y], new string(actual));   // names the first wrong row
        }
    }

    [Fact]
    public void The_creator_address_is_the_reference_version_3_symbol()
    {
        QrCode? qr = QrCode.Encode(ShortText);
        AssertMatrix(ShortMatrix, qr);
        Assert.Equal(3, qr!.Version);
        Assert.Equal(29, qr.Size);
        Assert.Equal(2, qr.Mask);
    }

    [Fact]
    public void A_120_character_address_is_the_reference_version_7_symbol()
    {
        Assert.Equal(120, LongText.Length);
        QrCode? qr = QrCode.Encode(LongText);
        AssertMatrix(LongMatrix, qr);
        Assert.Equal(7, qr!.Version);   // has version information
        Assert.Equal(4, qr.Mask);       // the mask segno would pick (3) scores worse with the format bits, as Nayuki counts them
    }

    [Fact]
    public void The_longest_text_that_fits_is_the_reference_version_10_symbol()
    {
        Assert.Equal(213, MaxText.Length);
        QrCode? qr = QrCode.Encode(MaxText);
        AssertMatrix(MaxMatrix, qr);
        Assert.Equal(10, qr!.Version);      // uneven blocks, 16-bit character count, version information
    }

    [Fact]
    public void Text_that_does_not_fit_version_10_gives_null()
    {
        Assert.NotNull(QrCode.Encode(new string('a', 213)));
        Assert.Null(QrCode.Encode(new string('a', 214)));
        Assert.Null(QrCode.Encode(new string('a', 5000)));
        // Capacity counts UTF-8 bytes, not characters: 107 two-byte letters are 214 bytes.
        Assert.Null(QrCode.Encode(new string('é', 107)));
        Assert.NotNull(QrCode.Encode(new string('é', 106)));
    }

    [Fact]
    public void The_smallest_version_that_holds_the_text_is_used()
    {
        // Byte capacity at level M: 14, 26, 42, 62, 84, 106, 122, 152, 180, 213 for versions 1 to 10.
        int[] capacity = [14, 26, 42, 62, 84, 106, 122, 152, 180, 213];
        for (int version = 1; version <= 10; version++)
        {
            Assert.Equal(version, QrCode.Encode(new string('x', capacity[version - 1]))!.Version);
            if (version < 10) Assert.Equal(version + 1, QrCode.Encode(new string('x', capacity[version - 1] + 1))!.Version);
        }
        Assert.Equal(1, QrCode.Encode("")!.Version);
    }

    [Fact]
    public void Modules_outside_the_symbol_are_light_and_the_finders_are_where_they_belong()
    {
        QrCode qr = QrCode.Encode(ShortText)!;
        Assert.False(qr.Get(-1, 0));
        Assert.False(qr.Get(0, -1));
        Assert.False(qr.Get(qr.Size, 0));
        Assert.False(qr.Get(0, qr.Size));
        // The three finder patterns have a dark corner module.
        Assert.True(qr.Get(0, 0));
        Assert.True(qr.Get(qr.Size - 1, 0));
        Assert.True(qr.Get(0, qr.Size - 1));
    }
